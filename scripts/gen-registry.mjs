#!/usr/bin/env node
/**
 * Module auto-discovery.
 *
 * Every server module is `src/server/modules/<name>/module.ts` with a default
 * export; every client feature is `src/client/modules/<name>/routes.tsx`
 * exporting `routes` (and optionally `nav`, `commands`, `widgets`). Nothing is
 * registered by hand, so parallel work never collides in a shared manifest.
 */
import { readdirSync, existsSync, writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => (existsSync(p) ? readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : []);
const ident = (name) => name.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));

/* ------------------------------ server ---------------------------------- */
const serverDir = join(root, 'src/server/modules');
const serverModules = read(serverDir).filter((n) => existsSync(join(serverDir, n, 'module.ts')));
const serverOut = [
  '// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.',
  "import type { ModuleDef } from '../kernel/module';",
  ...serverModules.map((n) => `import ${ident(n)} from '../modules/${n}/module';`),
  '',
  `export const MODULES: ModuleDef[] = [${serverModules.map(ident).join(', ')}];`,
  `export const MODULE_NAMES = [${serverModules.map((n) => JSON.stringify(n)).join(', ')}] as const;`,
  '',
].join('\n');
mkdirSync(join(root, 'src/server/generated'), { recursive: true });
writeFileSync(join(root, 'src/server/generated/registry.ts'), serverOut);

/* ------------------------------ client ---------------------------------- */
const clientDir = join(root, 'src/client/modules');
const clientModules = read(clientDir).filter((n) => existsSync(join(clientDir, n, 'routes.tsx')));
const exportsOf = (name) => {
  const src = readFileSync(join(clientDir, name, 'routes.tsx'), 'utf8');
  return {
    nav: /export\s+const\s+nav\b/.test(src),
    commands: /export\s+const\s+commands\b/.test(src),
    widgets: /export\s+const\s+widgets\b/.test(src),
    settings: /export\s+const\s+settings\b/.test(src),
  };
};
const meta = Object.fromEntries(clientModules.map((n) => [n, exportsOf(n)]));
const clientOut = [
  '// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.',
  "import type { RouteDef, NavItem, CommandDef, WidgetDef, SettingsPage } from '../kernel/registry-types';",
  ...clientModules.map((n) => `import * as ${ident(n)} from '../modules/${n}/routes';`),
  '',
  `export const ROUTES: RouteDef[] = [${clientModules.map((n) => `...(${ident(n)}.routes ?? [])`).join(', ')}];`,
  `export const NAV: NavItem[] = [${clientModules.filter((n) => meta[n].nav).map((n) => `...${ident(n)}.nav`).join(', ')}];`,
  `export const COMMANDS: CommandDef[] = [${clientModules.filter((n) => meta[n].commands).map((n) => `...${ident(n)}.commands`).join(', ')}];`,
  `export const WIDGETS: WidgetDef[] = [${clientModules.filter((n) => meta[n].widgets).map((n) => `...${ident(n)}.widgets`).join(', ')}];`,
  `export const SETTINGS_PAGES: SettingsPage[] = [${clientModules.filter((n) => meta[n].settings).map((n) => `...${ident(n)}.settings`).join(', ')}];`,
  '',
].join('\n');
mkdirSync(join(root, 'src/client/generated'), { recursive: true });
writeFileSync(join(root, 'src/client/generated/registry.tsx'), clientOut);

console.log(`registry: ${serverModules.length} server module(s), ${clientModules.length} client module(s)`);
